def _content(body: dict) -> str:
    msgs = body.get("messages") or []
    text = "\n".join(m.get("content") if isinstance(m.get("content"), str) else json.dumps(m.get("content")) for m in msgs)
    rf = body.get("response_format") or {}
    js = rf.get("json_schema") or {}
    name = js.get("name", "")
    schema = js.get("schema") or {}
    if name == "route":
        return json.dumps(_route(text))
    if name == "manifest" or "interface compiler" in text:
        return json.dumps(_manifest(text), indent=1)
    if schema:
        out = _fill(schema, schema.get("$defs") or {})
        if isinstance(out, dict) and "action" in out:
            out["action"] = "observe" if "class control" in text else "evacuate"
            out["escalate"] = "class control" not in text
            out["rationale"] = "[test] commander rationale"
        if isinstance(out, dict) and "recommends" in out:
            out["recommends"] = "evacuate"
        return json.dumps(out)
    return json.dumps({"note": "[test] free text reply"})


