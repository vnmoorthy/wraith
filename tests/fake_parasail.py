@app.post("/v1/embeddings")
async def embeddings(req: Request):
    body = await req.json()
    inputs = body["input"] if isinstance(body["input"], list) else [body["input"]]
    data = []
    for i, text in enumerate(inputs):
        vec = [0.0] * 128
        for w in re.findall(r"[a-z0-9]+", text.lower()):
            vec[int(hashlib.md5(w.encode()).hexdigest(), 16) % 128] += 1.0
        data.append({"object": "embedding", "index": i, "embedding": vec})
    return {"object": "list", "data": data, "model": body.get("model"), "usage": {"prompt_tokens": 1, "total_tokens": 1}}


@app.post("/v1/chat/completions")
async def chat(req: Request):
    body = await req.json()
    LOG.append({"t": time.time(), "model": body.get("model"), "stream": body.get("stream"),
                "rf": (body.get("response_format") or {}).get("type"), "name": ((body.get("response_format") or {}).get("json_schema") or {}).get("name")})
    content = _content(body)
    rid = "chatcmpl-test"
    if not body.get("stream"):
        await asyncio.sleep(0.4)
        return JSONResponse({"id": rid, "object": "chat.completion", "created": int(time.time()), "model": body.get("model"),
                             "choices": [{"index": 0, "message": {"role": "assistant", "content": content}, "finish_reason": "stop"}],
                             "usage": {"prompt_tokens": 10, "completion_tokens": 10, "total_tokens": 20}})

    async def gen():
        for i in range(0, len(content), 12):
            chunk = {"id": rid, "object": "chat.completion.chunk", "created": int(time.time()), "model": body.get("model"),
                     "choices": [{"index": 0, "delta": {"role": "assistant", "content": content[i:i + 12]} if i == 0 else {"content": content[i:i + 12]}, "finish_reason": None}]}
            yield f"data: {json.dumps(chunk)}\n\n"
            await asyncio.sleep(0.012)
        end = {"id": rid, "object": "chat.completion.chunk", "created": int(time.time()), "model": body.get("model"),
               "choices": [{"index": 0, "delta": {}, "finish_reason": "stop"}]}
        yield f"data: {json.dumps(end)}\n\n"
        if (body.get("stream_options") or {}).get("include_usage"):
            usage = {"id": rid, "object": "chat.completion.chunk", "created": int(time.time()), "model": body.get("model"), "choices": [],
                     "usage": {"prompt_tokens": 10, "completion_tokens": 10, "total_tokens": 20}}
            yield f"data: {json.dumps(usage)}\n\n"
        yield "data: [DONE]\n\n"

    return StreamingResponse(gen(), media_type="text/event-stream")


