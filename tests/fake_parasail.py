def _fill(schema: dict, defs: dict, key: str = "") -> object:
    if "$ref" in schema:
        return _fill(defs[schema["$ref"].split("/")[-1]], defs, key)
    if "anyOf" in schema:
        return _fill(schema["anyOf"][0], defs, key)
    if "enum" in schema:
        return schema["enum"][0]
    t = schema.get("type")
    if t == "object":
        return {k: _fill(v, defs, k) for k, v in (schema.get("properties") or {}).items()}
    if t == "array":
        return [_fill(schema.get("items") or {"type": "string"}, defs, key)]
    if t == "number":
        return 0.82
    if t == "integer":
        return 4
    if t == "boolean":
        return True
    return f"[test] {key}"


